const DICTS = { es, en }

// Saved choice, otherwise the browser language (Spanish browsers get Spanish, everyone else English)
function initial(): Lang {
  try {
    const saved = localStorage.getItem('lang')
    if (saved === 'es' || saved === 'en') return saved
  } catch { /* storage unavailable */ }
  return navigator.language.toLowerCase().startsWith('es') ? 'es' : 'en'
}

let current = initial()
document.documentElement.lang = current
const listeners = new Set<() => void>()

export function setLang(l: Lang) {
  current = l
  document.documentElement.lang = l
  try { localStorage.setItem('lang', l) } catch { /* storage unavailable */ }
  listeners.forEach(f => f())
}

export const getLang = () => current
export const texts = () => DICTS[current]

export function useT() {
  const lang = useSyncExternalStore(f => { listeners.add(f); return () => listeners.delete(f) }, getLang)
  return { t: DICTS[lang], lang }
}
